// Token Radar — the ranking model (radar-2).
//
// The entry's claim, in one paragraph: a pre-token protocol is worth what the
// market already pays for the same kind of protocol, scaled by how fast it is
// growing and how long it has run without a token. The market price for a kind
// of protocol is read out of this very snapshot — the median market-cap-per-TVL
// of the live-token protocols in the same category — never from a list of names
// typed in by hand. A category with too few live peers falls back to the
// snapshot-wide median. No protocol name is ever special-cased: one function
// scores every row, and the dashboard shows every factor it used.
//
//   multiple  = median(mcap_usd / tvl_usd) over live-token protocols in the
//               same category (n >= 3), clamped to [0.05, 1.5]; otherwise the
//               snapshot-wide median of the same ratio.
//   growth    = clamp(change_7d, -60, 120) percent
//   growthMul = 1 + (growth / 100) * 0.5
//   maturity  = 0.6 + min(age_days, 1095) / 1095 * 0.4   (age unknown: 365 days)
//   implied   = max(1, round(tvl_usd * multiple * growthMul * maturity))
//
// The board ranks the snapshot's watchlist (the floor: every pre-token
// protocol at or above $50M TVL that is not a wrapped, staked or bridged
// product) plus the 160 pre-token protocols below the floor with the most TVL
// — the early rows a radar exists to find. Live-token protocols are kept apart
// in their own view at their market caps, never mixed into the ranked board.

/** One protocol record, exactly the ten fields the sealed snapshot carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The sealed snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's tunable constants, stated on the dashboard and in the page. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  multiple_floor: number;
  multiple_cap: number;
  min_peers: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  multiple_floor: 0.05,
  multiple_cap: 1.5,
  min_peers: 3,
};

/** This model's version label, shown on the dashboard. */
export const MODEL_VERSION = 'radar-2';

